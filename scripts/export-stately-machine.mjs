#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const sourcePath = path.join(repoRoot, 'src', 'mascot-v2', 'behavior-machine.js');
const outDir = path.join(repoRoot, 'docs', 'stately');
const jsonPath = path.join(outDir, 'hermes-display.machine.json');
const tsPath = path.join(outDir, 'hermes-display.stately.ts');

const source = fs.readFileSync(sourcePath, 'utf8');
let capturedConfig = null;
const sandbox = {
  window: {
    XState: {
      createMachine(config) {
        capturedConfig = config;
        return config;
      },
    },
  },
  console,
};
vm.createContext(sandbox);
vm.runInContext(source, sandbox, { filename: sourcePath });

const api = sandbox.window.HermesBehaviorMachine;
if (!api?.createXStateMachine) {
  throw new Error('HermesBehaviorMachine.createXStateMachine was not exposed by behavior-machine.js');
}

const machineConfig = api.createXStateMachine(api.REGION_DEFAULTS);
if (!machineConfig || capturedConfig !== machineConfig) {
  throw new Error('Failed to capture the XState machine config');
}

fs.mkdirSync(outDir, { recursive: true });
const machineJson = JSON.stringify(machineConfig, null, 2);
fs.writeFileSync(jsonPath, `${machineJson}\n`);
fs.writeFileSync(
  tsPath,
  `// Generated by scripts/export-stately-machine.mjs from src/mascot-v2/behavior-machine.js\n` +
    `// Import this with the Import button in https://stately.ai/registry/editor/.\n` +
    `// The Stately importer expects a createMachine(...) factory call.\n\n` +
    `createMachine(${machineJson});\n`
);

console.log(`Wrote ${path.relative(repoRoot, tsPath)}`);
console.log(`Wrote ${path.relative(repoRoot, jsonPath)}`);
console.log(`States: ${Object.keys(machineConfig.states || {}).join(', ')}`);
