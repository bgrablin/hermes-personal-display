#!/usr/bin/env node
'use strict';

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const runtimeHtmlPath = path.join(projectRoot, 'src', 'character-runtime.html');
const generatedBuildIdPath = path.join(projectRoot, 'src', 'generated', 'build-id.js');
const BUILD_ID_RE = /window\.__HERMES_DISPLAY_BUILD_ID\s*=\s*['"]([^'"]+)['"]/;

const HASH_PREFIX = 'h';
const HASH_LENGTH = 12;

const STATIC_RUNTIME_FILES = [
  'src/styles.css',
  'src/generated/display-contract.js',
  'src/state.js',
  'src/mascot/sanitize.js',
  'src/mascot/behavior-machine.js',
  'src/mascot/states.js',
  'src/mascot/motion-adapter.js',
  'src/mascot/audio.js',
  'src/mascot/touch-fx.js',
  'src/mascot/entertainment.js',
  'src/mascot/watch-sequences.js',
  'src/mascot/sequences.json',
  'src/mascot/app.js',
];

function firstPartyAssetRef(ref) {
  return ref.startsWith('./') && !ref.startsWith('./vendor/');
}

function htmlRefToRuntimePath(ref) {
  const [withoutQuery] = ref.split('?');
  const [withoutHash] = withoutQuery.split('#');
  if (!firstPartyAssetRef(withoutHash)) return null;
  return path.posix.join('src', withoutHash.slice(2));
}

function htmlRuntimeAssetRefs(html) {
  const refs = new Set();
  const refPattern = /<(?:script|link)\b[^>]*\s(?:src|href)=["']([^"']+)["']/g;
  for (const match of html.matchAll(refPattern)) {
    const runtimePath = htmlRefToRuntimePath(match[1]);
    if (runtimePath) refs.add(runtimePath);
  }
  return refs;
}

function assertRuntimeAssetListMatchesHtml(html) {
  const htmlRefs = htmlRuntimeAssetRefs(html);
  // build-id.js is the generated artifact that publishes the computed id; including it
  // in the hash input would create a self-referential loop. Debug HTML links are not
  // kiosk runtime assets.
  htmlRefs.delete('src/generated/build-id.js');
  htmlRefs.delete('src/mascot-debug.html');

  const hashedFiles = new Set(STATIC_RUNTIME_FILES.filter((file) => file !== 'src/mascot/sequences.json'));
  const missingFromHash = [...htmlRefs].filter((file) => !hashedFiles.has(file));
  const missingFromHtml = [...hashedFiles].filter((file) => !htmlRefs.has(file));
  if (missingFromHash.length || missingFromHtml.length) {
    const parts = [];
    if (missingFromHash.length) parts.push(`HTML first-party refs missing from STATIC_RUNTIME_FILES: ${missingFromHash.join(', ')}`);
    if (missingFromHtml.length) parts.push(`STATIC_RUNTIME_FILES not directly versioned in HTML: ${missingFromHtml.join(', ')}`);
    throw new Error(parts.join('; '));
  }
}

function normalizeRuntimeHtmlForHash(html) {
  // The HTML participates in the content hash, but first-party cache keys do not.
  // Otherwise regenerating ?v=<hash> would change the next hash forever.
  return html.replace(/(<(?:script|link)\b[^>]*\s(?:src|href)=")((?:\.\/)(?!vendor\/)[^"]*?)\?v=[^"#?]*([^"]*")/g, '$1$2$3');
}

function readIfExists(relativePath) {
  const absolutePath = path.join(projectRoot, relativePath);
  if (!fs.existsSync(absolutePath)) return null;
  return fs.readFileSync(absolutePath);
}

function computeBuildId() {
  const hash = crypto.createHash('sha256');
  hash.update('hermes-personal-display-runtime-build-id-v1\n');
  const runtimeHtml = ensureBuildIdScriptPresent(fs.readFileSync(runtimeHtmlPath, 'utf8'), 'generated');
  assertRuntimeAssetListMatchesHtml(runtimeHtml);
  hash.update('src/character-runtime.html\n');
  hash.update(normalizeRuntimeHtmlForHash(runtimeHtml));
  hash.update('\n');
  for (const relativePath of STATIC_RUNTIME_FILES) {
    const content = readIfExists(relativePath);
    if (content === null) throw new Error(`missing runtime hash input: ${relativePath}`);
    hash.update(relativePath);
    hash.update('\0');
    hash.update(content);
    hash.update('\n');
  }
  return `${HASH_PREFIX}${hash.digest('hex').slice(0, HASH_LENGTH)}`;
}

function generatedBuildIdSource(buildId) {
  return `// Generated by scripts/generate-build-id.js. Do not edit by hand.\n// This id is a deterministic content hash of first-party kiosk runtime assets.\nwindow.__HERMES_DISPLAY_BUILD_ID = '${buildId}';\n`;
}

function rewriteFirstPartyAssetVersions(html, buildId) {
  return html.replace(/(<(?:script|link)\b[^>]*\s(?:src|href)=")([^"]+)(")/g, (match, prefix, ref, suffix) => {
    const [base, queryAndHash = ''] = ref.split('?');
    if (!firstPartyAssetRef(base)) return match;
    const hashIndex = queryAndHash.indexOf('#');
    const hashSuffix = hashIndex >= 0 ? queryAndHash.slice(hashIndex) : '';
    return `${prefix}${base}?v=${buildId}${hashSuffix}${suffix}`;
  });
}

function currentGeneratedBuildId() {
  if (!fs.existsSync(generatedBuildIdPath)) return null;
  const source = fs.readFileSync(generatedBuildIdPath, 'utf8');
  return source.match(BUILD_ID_RE)?.[1] || null;
}

function ensureBuildIdScriptPresent(html, buildId) {
  if (html.includes('./generated/build-id.js')) return html;
  const script = `  <script src="./generated/build-id.js?v=${buildId}"></script>\n`;
  return html.replace('  <script src="./mascot/sanitize.js', `${script}  <script src="./mascot/sanitize.js`);
}

function generate({ check = false } = {}) {
  const buildId = computeBuildId();
  const buildIdSource = generatedBuildIdSource(buildId);
  const currentHtml = fs.readFileSync(runtimeHtmlPath, 'utf8');
  const desiredHtml = rewriteFirstPartyAssetVersions(ensureBuildIdScriptPresent(currentHtml, buildId), buildId);
  const currentGenerated = fs.existsSync(generatedBuildIdPath)
    ? fs.readFileSync(generatedBuildIdPath, 'utf8')
    : '';

  const stale = currentGenerated !== buildIdSource || currentHtml !== desiredHtml;
  if (check) {
    if (stale) {
      const existing = currentGeneratedBuildId() || 'missing';
      throw new Error(`build id artifacts are stale: expected ${buildId}, found ${existing}; run npm run generate:build-id`);
    }
    return { buildId, stale: false };
  }

  fs.mkdirSync(path.dirname(generatedBuildIdPath), { recursive: true });
  if (currentGenerated !== buildIdSource) fs.writeFileSync(generatedBuildIdPath, buildIdSource);
  if (currentHtml !== desiredHtml) fs.writeFileSync(runtimeHtmlPath, desiredHtml);
  return { buildId, stale };
}

function main() {
  const check = process.argv.includes('--check');
  const result = generate({ check });
  console.log(`${result.buildId}${result.stale ? ' updated' : ''}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error.message || error);
    process.exit(1);
  }
}

export {
  BUILD_ID_RE,
  computeBuildId,
  currentGeneratedBuildId,
  generate,
  generatedBuildIdPath,
  normalizeRuntimeHtmlForHash,
  rewriteFirstPartyAssetVersions,
};
